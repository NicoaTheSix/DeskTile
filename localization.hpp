inline const Translation* FindTranslation(std::wstring_view text,bool acceptEnglish=false) {
    for(const auto& entry:Catalog)
        if(text==entry.chinese || (acceptEnglish && text==entry.english))return &entry;
    return nullptr;
}
inline const wchar_t* Tr(const wchar_t* key) {
    if(language==Language::English)if(auto entry=FindTranslation(key))return entry->english;
    return key;
}
inline std::wstring TrCounted(const wchar_t* key,std::size_t count) {
    std::wstring result=Tr(key);
    if(language==Language::English && count==1) {
        for(const auto& noun:{std::pair<std::wstring,std::wstring>{L" tiles",L" tile"},{L" fonts",L" font"}}) {
            auto at=result.find(noun.first);if(at!=std::wstring::npos)result.replace(at,noun.first.size(),noun.second);
        }
    }
    return result;
}
inline std::wstring LocalizeError(const std::wstring& error) {
    if(language==Language::English)if(auto entry=FindTranslation(error))return entry->english;
    return error;
}
inline const char* LanguageCode(Language value){return value==Language::English?"en":"zh-TW";}
